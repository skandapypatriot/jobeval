"""Safe local file storage and upload validation."""

from __future__ import annotations

import hashlib
import re
import shutil
from dataclasses import dataclass
from pathlib import Path
from typing import BinaryIO

from app.core.config import get_settings

_SAFE_CHARS = re.compile(r"[^A-Za-z0-9._-]+")


class StorageError(ValueError):
    """Raised when an upload violates a safety or content rule."""


@dataclass(frozen=True)
class StoredFile:
    path: Path
    relative_path: str
    original_filename: str
    extension: str
    mime_type: str
    size_bytes: int
    sha256: str


class LocalStorage:
    """Stores uploads below one configured root and never trusts a client path."""

    def __init__(self, root: Path | None = None, max_size: int | None = None) -> None:
        settings = get_settings()
        self.root = (root or settings.upload_root).resolve()
        self.max_size = max_size if max_size is not None else settings.max_file_size_bytes
        self.root.mkdir(parents=True, exist_ok=True)

    @staticmethod
    def sanitize_filename(filename: str | None) -> str:
        """Return a safe basename, rejecting traversal rather than hiding it."""

        raw = (filename or "").strip()
        if not raw:
            raise StorageError("A filename is required")
        if "\x00" in raw or any(ord(ch) < 32 for ch in raw):
            raise StorageError("Filename contains invalid control characters")
        # Treat both slash styles as separators.  Rejecting is safer than
        # silently accepting a traversal attempt.
        if "/" in raw or "\\" in raw or raw in {".", ".."} or ".." in Path(raw).parts:
            raise StorageError("Filename must not contain a path")
        name = Path(raw).name
        suffix = Path(name).suffix.lower()
        stem = Path(name).stem
        stem = _SAFE_CHARS.sub("_", stem).strip("._") or "upload"
        if len(stem) > 120:
            stem = stem[:120]
        safe = f"{stem}{suffix}"
        if len(safe.encode("utf-8")) > 240:
            raise StorageError("Filename is too long")
        return safe

    def _validate_extension(self, filename: str) -> str:
        suffix = Path(filename).suffix.lower()
        allowed = {x.lower() for x in get_settings().ALLOWED_EXTENSIONS}
        if suffix not in allowed:
            allowed_text = ", ".join(sorted(allowed))
            raise StorageError(
                f"Unsupported file extension '{suffix or '<none>'}'. Allowed: {allowed_text}"
            )
        return suffix

    @staticmethod
    def _sniff(content: bytes, extension: str) -> tuple[str, str]:
        """Return (mime type, detected kind), rejecting mismatched content."""

        if not content:
            raise StorageError("Uploaded file is empty")
        head = content[:4096]
        if extension in {".step", ".stp"}:
            try:
                text = head.decode("utf-8", errors="ignore").upper()
            except Exception as exc:  # pragma: no cover - defensive
                raise StorageError("Could not inspect STEP content") from exc
            if "ISO-10303" not in text and "FILE_SCHEMA" not in text:
                raise StorageError("File extension does not match STEP content")
            return "application/step", "step"
        if extension == ".pdf":
            if not content.startswith(b"%PDF-"):
                raise StorageError("File extension does not match PDF content")
            return "application/pdf", "pdf"
        if extension == ".dxf":
            if content.startswith(b"AutoCAD Binary DXF"):
                return "image/vnd.dxf", "dxf"
            try:
                text = content.decode("utf-8", errors="ignore").upper()
            except Exception as exc:  # pragma: no cover
                raise StorageError("Could not inspect DXF content") from exc
            if "SECTION" not in text or "HEADER" not in text:
                raise StorageError("File extension does not match DXF content")
            return "image/vnd.dxf", "dxf"
        raise StorageError(f"No content validator is available for '{extension}'")

    def save_upload(self, project_id: str, filename: str, source: BinaryIO) -> StoredFile:
        """Validate and atomically save an upload."""

        safe_name = self.sanitize_filename(filename)
        extension = self._validate_extension(safe_name)
        project_root = (self.root / project_id).resolve()
        project_root.mkdir(parents=True, exist_ok=True)
        # The stored name is generated by the server, not derived from a path.
        import uuid

        file_id = uuid.uuid4().hex
        stored_name = f"{file_id}{extension}"
        destination = (project_root / stored_name).resolve()
        if not self._is_under(destination, self.root):
            raise StorageError("Unsafe storage destination")

        temporary = destination.with_suffix(destination.suffix + ".part")
        digest = hashlib.sha256()
        size = 0
        first = b""
        try:
            with temporary.open("wb") as output:
                while True:
                    chunk = source.read(1024 * 1024)
                    if not chunk:
                        break
                    if not first:
                        first = chunk[:4096]
                    size += len(chunk)
                    if size > self.max_size:
                        raise StorageError(
                            f"File exceeds the maximum upload size of {self.max_size // (1024 * 1024)} MB"
                        )
                    digest.update(chunk)
                    output.write(chunk)
            self._sniff(first, extension)
            temporary.replace(destination)
        except Exception:
            temporary.unlink(missing_ok=True)
            raise

        relative = destination.relative_to(self.root).as_posix()
        mime, _kind = self._sniff(first, extension)
        return StoredFile(
            path=destination,
            relative_path=relative,
            original_filename=safe_name,
            extension=extension,
            mime_type=mime,
            size_bytes=size,
            sha256=digest.hexdigest(),
        )

    def delete(self, relative_path: str) -> None:
        path = self.resolve(relative_path)
        if path.exists():
            path.unlink()
        # Remove empty project directories, but never the root.
        parent = path.parent
        try:
            parent.rmdir()
        except OSError:
            pass

    def resolve(self, relative_path: str) -> Path:
        """Resolve a stored relative path and reject traversal."""

        candidate = (self.root / relative_path).resolve()
        if not self._is_under(candidate, self.root):
            raise StorageError("Unsafe file path")
        return candidate

    @staticmethod
    def _is_under(path: Path, root: Path) -> bool:
        try:
            path.relative_to(root)
            return True
        except ValueError:
            return False

    def copy_into(self, source: Path, project_id: str, filename: str) -> StoredFile:
        """Copy a trusted local source into managed storage."""

        with source.open("rb") as stream:
            return self.save_upload(project_id, filename, stream)


def remove_tree(path: Path) -> None:
    """Remove a directory tree if it exists (used for project cleanup)."""

    if path.exists() and path.is_dir():
        shutil.rmtree(path)
